"""System check for a BC-250 running this package: what the qualified experience depends on outside the game folder.
Other GPUs get a GPU line about what runs there (Intel's shaders unless the experimental BC250_XEFG_ANY_GPU=1 opt-in) and
no BC-250-only checks. The lines follow the package beside this file (its manifest.json): the enabler-free build
(libxess_fg.dll proxy, 2x on non-Intel GPUs) promises neither pacing nor Scale/Limit on other GPUs.

`install.py doctor` prints one line per item (OK / WARN / INFO) with what to do. Nothing is changed.
"""
import ctypes, json, os, re, shutil, socket, subprocess
from pathlib import Path

BC250 = 0x13fe


def _read(path):
    try:
        return Path(path).read_text().strip()
    except OSError:
        return None


DRM = Path('/sys/class/drm')


def gpus(drm=None):
    """[(vendor, device, sysfs device directory)] of every DRM card, as hex strings ('0x1002', '0x13fe')."""
    found = []
    for card in sorted(Path(drm or DRM).glob('card[0-9]*')):
        if '-' in card.name:  # connectors (card0-DP-1) share the prefix
            continue
        vendor, device = _read(card/'device/vendor'), _read(card/'device/device')
        if vendor and device and (vendor, device) not in [(v, d) for v, d, _ in found]:
            found.append((vendor, device, card/'device'))
    return found


def gpu_card(drm=None):
    for vendor, device, path in gpus(drm):
        if device == hex(BC250) and vendor == '0x1002':
            return path
    return None


PROXY_ENTRY = 'libxess_fg-proxy'
# The kernel the latest checks ran on (linux-cachyos-bc250 carries the BC-250 display and compute-queue patches).
KERNEL = 'linux-cachyos-bc250 7.2.8-1.219'


def package_info(package=None):
    """What the package beside this file does, from its manifest.json: proxy (the enabler-free libxess_fg.dll proxy over
    Intel's unmodified runtime, 2x only, logs beside the game executable), scaling (generated-frame Scale/Limit: the
    profile marker install.py configure also checks), max_factor. None without a readable manifest (the source tree)."""
    try:
        manifest = json.loads((Path(package or Path(__file__).resolve().parent)/'manifest.json').read_text())
        files = manifest['files']
    except (OSError, ValueError, KeyError, TypeError):
        return None
    proxy = manifest.get('addon_entry') == PROXY_ENTRY
    return dict(proxy=proxy, scaling=any(name.endswith('BC250-XeFG/shaders/mfg-frame-settings.required') for name in files),
                max_factor=manifest.get('max_factor', 2 if proxy else 4))


def any_gpu_text(info):
    """The GPU line's text for a GPU other than the BC-250: what runs there, and the experimental opt-in."""
    opt_in = ('BC250_XEFG_ANY_GPU=1 in a game\'s launch options (before %command%; in Heroic as an environment variable) is an '
              'experimental opt-in, untested outside the BC-250')
    if info and info['proxy']:
        # Intel's runtime generates one frame per real frame on non-Intel GPUs; on an Intel GPU it allows more, and the
        # proxy leaves such a context to Intel's shaders (src/game/mfg_proxy.c). Only the OptiScaler routes are set to 2x.
        return ('XeFG still runs there with Intel\'s own shaders and generated frames at output resolution: 2x on a '
                'non-Intel GPU (the most Intel\'s runtime generates there); on an Intel GPU a native XeSS FG game\'s own '
                'setting can ask for more (the installer sets the OptiScaler routes to 2x). This build paces only frames '
                'generated by its own shaders, so presents on that GPU are not paced, and it has no Scale/Limit settings. ' +
                opt_in + ': it runs this build\'s shaders on that GPU for one generated frame per real frame (a context asking '
                'for more keeps Intel\'s shaders; pacing there is untested too). If that game then closes or shows wrong '
                'frames, remove it again (BC250-MFG.log and BC250-XeFG-fast.log beside the game\'s executable say why).')
    scaling = info is None or info['scaling']
    return ('XeFG still runs there with Intel\'s shaders and generated frames at output resolution; the pacing layer follows '
            'XeFG\'s own frame count there (checked on the BC-250 with BC250_XEFG_DISABLE=1, not on other GPUs). ' + opt_in +
            ': it tries the BC-250 optimisations' + (' and the Scale/Limit settings' if scaling else '') + ' on that GPU. If '
            'that game then closes or shows wrong frames, remove it again (BC250-XeFG-fast.log in OptiScaler/plugins says why).')


def build_text(info):
    if info['proxy']:
        return ('2x: one generated frame per real frame (the most Intel\'s runtime generates on a non-Intel GPU; on an '
                'Intel GPU a native XeSS FG game may ask Intel\'s shaders for more), from this '
                'package\'s libxess_fg.dll over Intel\'s unmodified XeFG runtime; generated frames always match the output '
                '(no Scale/Limit settings); presents are paced while its own shaders generate (not with '
                'BC250_XEFG_DISABLE=1, which runs Intel\'s shaders); logs beside the game\'s executable')
    return (f'up to {info["max_factor"]}x through the XeSSMFG enabler; ' +
            ('Scale/Limit settings for generated frames' if info['scaling'] else 'generated frames match the output (no Scale/Limit settings)') +
            '; logs in OptiScaler/plugins')


def vulkan_queue_families():
    """[(flags, count)] of the first AMD 0x13fe Vulkan device, through the Vulkan loader (no helper tools)."""
    try:
        vk = ctypes.CDLL('libvulkan.so.1')
    except OSError:
        return None
    class AppInfo(ctypes.Structure):
        _fields_ = [('sType', ctypes.c_int), ('pNext', ctypes.c_void_p), ('pApplicationName', ctypes.c_char_p),
                    ('applicationVersion', ctypes.c_uint32), ('pEngineName', ctypes.c_char_p), ('engineVersion', ctypes.c_uint32),
                    ('apiVersion', ctypes.c_uint32)]
    class CreateInfo(ctypes.Structure):
        _fields_ = [('sType', ctypes.c_int), ('pNext', ctypes.c_void_p), ('flags', ctypes.c_uint32), ('pApplicationInfo', ctypes.POINTER(AppInfo)),
                    ('enabledLayerCount', ctypes.c_uint32), ('ppEnabledLayerNames', ctypes.c_void_p),
                    ('enabledExtensionCount', ctypes.c_uint32), ('ppEnabledExtensionNames', ctypes.c_void_p)]
    class Family(ctypes.Structure):
        _fields_ = [('queueFlags', ctypes.c_uint32), ('queueCount', ctypes.c_uint32), ('timestampValidBits', ctypes.c_uint32),
                    ('minImageTransferGranularity', ctypes.c_uint32 * 3)]
    app = AppInfo(0, None, b'bc250-doctor', 1, None, 0, (1 << 22) | (1 << 12))
    info = CreateInfo(1, None, 0, ctypes.pointer(app), 0, None, 0, None)
    instance = ctypes.c_void_p()
    env = {k: os.environ.pop(k) for k in ('VK_INSTANCE_LAYERS', 'VK_LOADER_LAYERS_ENABLE') if k in os.environ}
    try:
        if vk.vkCreateInstance(ctypes.byref(info), None, ctypes.byref(instance)):
            return None
        count = ctypes.c_uint32(0)
        vk.vkEnumeratePhysicalDevices(instance, ctypes.byref(count), None)
        devices = (ctypes.c_void_p * count.value)()
        vk.vkEnumeratePhysicalDevices(instance, ctypes.byref(count), devices)
        result = None
        for device in devices:
            # VkPhysicalDeviceProperties is 824 bytes on x86-64; only vendorID/deviceID (offsets 8 and 12) are read.
            props = (ctypes.c_uint32 * 512)()
            vk.vkGetPhysicalDeviceProperties(ctypes.c_void_p(device), props)
            if props[2] == 0x1002 and props[3] == BC250:
                n = ctypes.c_uint32(0)
                vk.vkGetPhysicalDeviceQueueFamilyProperties(ctypes.c_void_p(device), ctypes.byref(n), None)
                families = (Family * n.value)()
                vk.vkGetPhysicalDeviceQueueFamilyProperties(ctypes.c_void_p(device), ctypes.byref(n), families)
                result = [(f.queueFlags, f.queueCount) for f in families]
                break
        vk.vkDestroyInstance(instance, None)
        return result
    finally:
        os.environ.update(env)


def kernel_compute_fixes():
    """Evidence that the kernel carries the GFX1013 compute-queue fixes (PASID TLB flushes through MMIO, a GFXOFF guard for
    compute), which a driver with the compute queue enabled needs; None when nothing shows them (no version or ioctl
    reports them, so these are heuristics)."""
    if Path('/sys/module/amdgpu/parameters/bc250_flush_by_runlist').exists():
        return 'BC-250 kernel with the compute-queue fixes (MastaG linux-cachyos-bc250)'
    try:
        out=subprocess.run(['journalctl','-k','-b','-q','-o','cat','-n','1','-g','GFX1013/BC-250: using MMIO PASID TLB flushes'],
                           capture_output=True,text=True,timeout=10).stdout.strip()
    except (OSError,subprocess.SubprocessError):
        out=''
    if out:return 'kernel log: '+out
    if 'skillfish' in os.uname().release.lower():return 'SkillFishOS kernel '+os.uname().release
    return None


# Per-game drivers with the compute queue that other BC-250 projects install without replacing the system Mesa.
SIDE_DRIVERS=[('/usr/local/lib/bc250-radv/share/vulkan/icd.d','bc250-async-compute-bazzite'),('/opt/bc250-gfx1013/share/vulkan/icd.d','bc250-gfx1013-fix')]


def checks(home=None, drm=None, package=None):
    home = Path(home or Path.home())
    info = package_info(package)
    rows = []
    def add(level, item, text):
        rows.append((level, item, text))
    card = gpu_card(drm)
    others = ', '.join(v.removeprefix('0x') + ':' + d.removeprefix('0x') for v, d, _ in gpus(drm))
    add('OK' if card else 'WARN', 'GPU', 'AMD BC-250 (Cyan Skillfish, 0x13fe)' if card else
        (f'{others}: not a BC-250' if others else 'No BC-250 GPU found') + '; this package is qualified on the BC-250 only. ' + any_gpu_text(info))
    if info:
        add('INFO', 'Build', build_text(info))
    add('INFO', 'Kernel', os.uname().release + f' (checked on {KERNEL}; other kernels untested)')
    if card:  # the compute-queue, memory and clock checks are about the BC-250
        families = vulkan_queue_families()
        if families is None:
            add('WARN', 'Vulkan', 'Could not query the BC-250 through Vulkan (libvulkan missing or no RADV device).')
        else:
            dedicated = [(f, c) for f, c in families if f & 2 and not f & 1 and c > 1]
            fixes = kernel_compute_fixes()
            if dedicated and not fixes:
                add('WARN', 'Compute queue', 'The driver exposes a dedicated compute queue, but nothing shows that this kernel has the '
                    'BC-250 compute-queue fixes (MMIO PASID TLB flushes, compute GFXOFF guard). Without them games can hang or '
                    'corrupt; use the kernel that belongs with this Mesa build.')
            elif dedicated:
                add('OK', 'Compute queue', 'Dedicated compute queue present; ' + fixes + '.')
            else:
                side = [f'{name} ({folder})' for folder, name in SIDE_DRIVERS if Path(folder).is_dir()]
                add('INFO', 'Compute queue', 'No dedicated compute queue (stock Mesa disables it on the BC-250). Frame pacing does '
                    'not need it (the layer presents from the game\'s queue); it lets games run async compute, which a patched '
                    'Mesa together with a patched kernel provides: Arch/CachyOS MastaG\'s [bc250-cachyos] repository, Bazzite '
                    'bc250-async-compute-bazzite, Fedora bc250-gfx1013-fix.' + (' Installed per game: ' + ', '.join(side) +
                    ' (VK_DRIVER_FILES in the game\'s launch options).' if side else ''))
    if card:
        gtt = _read(card/'mem_info_gtt_total')
        vram = _read(card/'mem_info_vram_total')
        if gtt and vram:
            g, v = int(gtt) / 2**30, int(vram) / 2**30
            add('OK' if g >= 5.5 else 'INFO', 'Memory', f'VRAM {v:.1f} GiB, GTT {g:.1f} GiB' +
                ('' if g >= 5.5 else '; the qualification host uses ttm.pages_limit=1572864 (6 GiB GTT) for 1440p/4K frame generation'))
        sclk = _read(card/'pp_dpm_sclk')
        if sclk:
            top = max((int(m) for m in re.findall(r'(\d+)Mhz', sclk)), default=0)
            add('OK' if top >= 1500 else 'INFO', 'GPU clock', f'highest DPM level {top} MHz' +
                ('' if top >= 1500 else '; published numbers were measured with a governor at 1850 MHz (e.g. cyan-skillfish-governor)'))
    gs = shutil.which('gamescope')
    if gs:
        try:
            version = re.search(r'gamescope version (\S+)', subprocess.run([gs, '--version'], capture_output=True, text=True, timeout=10).stderr + '')
        except (OSError, subprocess.SubprocessError):
            version = None
        v = version[1] if version else 'unknown'
        old = version and tuple(int(x) for x in re.findall(r'\d+', v)[:3]) < (3, 16, 28)
        add('WARN' if old else 'OK', 'gamescope', v + (' (pacing was qualified on 3.16.28; older builds were not tested)' if old else ''))
        real = os.path.realpath(gs)
        try:
            with open(real, 'rb') as stream:
                elf = stream.read(4) == b'\x7fELF'
        except OSError:
            elf = False
        if not elf:
            add('INFO', 'gamescope priority', f'{gs} is a wrapper, not the gamescope program; check CAP_SYS_NICE on the real binary')
        elif not shutil.which('getcap'):
            add('INFO', 'gamescope priority', 'cannot check CAP_SYS_NICE: getcap is not installed (libcap)')
        else:
            caps = subprocess.run(['getcap', real], capture_output=True, text=True).stdout
            add('OK' if 'cap_sys_nice' in caps else 'WARN', 'gamescope priority',
                'CAP_SYS_NICE set' if 'cap_sys_nice' in caps else
                'gamescope lacks CAP_SYS_NICE, so its composition waits behind game work (uneven VRR refresh with FG). '
                'Run extras/gamescope-cap-sys-nice/install.sh' +
                (' (sets it; on pacman systems a hook keeps it across updates).' if Path('/etc/pacman.d').is_dir() else
                 ' (sets it; run it again after a gamescope update).'))
    else:
        add('INFO', 'gamescope', 'not found; frame pacing applies only under gamescope (Steam Game Mode)')
    tools = []
    for folder in (home/'.steam/root/compatibilitytools.d', home/'.local/share/Steam/compatibilitytools.d',
                   home/'.var/app/com.valvesoftware.Steam/.local/share/Steam/compatibilitytools.d',
                   Path('/usr/share/steam/compatibilitytools.d')):  # distribution packages (proton-ge-custom)
        tools += [p.name for p in folder.glob('*GE-Proton*') if p.is_dir()]
    tools = sorted(set(tools))
    add('OK' if any(re.match(r'GE-Proton11-[67]\b', t) for t in tools) else 'INFO', 'Proton',
        (', '.join(tools) if tools else 'no GE-Proton found') + '; qualified on GE-Proton11-6/11-7 (other Proton builds untested)')
    missing = [t for t in ('zenity', 'bsdtar') if not shutil.which(t)]
    add('OK' if not missing else 'WARN', 'Setup tools', 'zenity and bsdtar present' if not missing else 'missing: ' + ', '.join(missing))
    try:
        with socket.create_connection(('127.0.0.1', 8080), timeout=0.3):
            listening = True
    except OSError:
        listening = False
    flag = any((b/'.cef-enable-remote-debugging').exists() for b in (home/'.steam/steam', home/'.local/share/Steam'))
    add('OK' if listening or flag else 'INFO', 'Steam DevTools',
        'reachable on 127.0.0.1:8080 (for extras/steam-screensaver-in-game)' if listening else
        'enabled for the next Steam start (for extras/steam-screensaver-in-game)' if flag else
        'not reachable; only needed by the optional Steam screensaver helper (Decky Loader enables it, or '
        'touch ~/.steam/steam/.cef-enable-remote-debugging and restart Steam)')
    return rows


def main(home=None, package=None):
    rows = checks(home, package=package)
    width = max(len(r[1]) for r in rows)
    for level, item, text in rows:
        print(f'{level:4}  {item:<{width}}  {text}')
    return 0 if all(r[0] != 'WARN' for r in rows) else 1


if __name__ == '__main__':
    raise SystemExit(main())
